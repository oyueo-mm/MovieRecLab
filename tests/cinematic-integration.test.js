'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const shell=read('cinematic/index.html');
const js=read('cinematic/shell.js');
const css=read('cinematic/shell.css');
const theme=read('cinematic/theme.css');
new vm.Script(js,{filename:'cinematic/shell.js'});
assert.match(shell,/<iframe[^>]+src="\.\.\/index\.html"/,'cinematic mode must embed the untouched original application');
assert.match(shell,/src="\.\/shell\.js"/,'cinematic mode must boot its dedicated shell');
assert.match(shell,/rel="stylesheet" href="\.\/shell\.css"/);
for(const id of ['cinematic','appFrame','appStage','enter','backIntro','openMenu','menuVeil','menuPanel','closeMenu','toggleMotion','toggleLanguage','stageLabel','alert'])assert.match(shell,new RegExp('id="'+id+'"'),'missing shell ID '+id);
for(const tab of ['recommend','compare','analysis','visualize','evaluate','guide'])assert.match(shell,new RegExp('data-target="'+tab+'"'),'missing legacy tab '+tab);
assert.match(js,/new URL\('\.\/theme\.css',window\.location\.href\)/,'inject exact same-origin skin path');
assert.match(js,/contentDocument/,'bridge must remain same-origin');
assert.match(js,/MutationObserver/,'movie visuals must update after recommendation changes');
assert.match(js,/onboardPreset/,'preset flow must be observed');
assert.match(js,/onboardingSubmit/,'rating completion must be observed');
assert.match(js,/data-target/,'navigate using existing tabs, not a second recommendation engine');
assert.match(css,/prefers-reduced-motion/,'respect system motion preferences');
assert.match(theme,/\.onboard-grid/);
assert.match(theme,/#recResults/);
assert.match(theme,/\.tab:not\(#recommend\)/,'research modules must remain legible');
assert.match(theme,/#recommendWorkspace\[hidden\]/,'original hidden state must be preserved');
assert.doesNotMatch(shell,/<script[^>]+src="\.\.\/app\.js"/,'the iframe, not the shell, owns the application runtime');
assert.match(read('index.html'),/id="onboardingGate"/);
assert.match(read('index.html'),/id="recommendWorkspace"/);
assert.match(read('index.html'),/id="recResults"/);
console.log('Cinematic integration smoke checks passed. Original recommendation engine is untouched.');

assert.match(shell,/id="sceneViewport"/,'pinned camera viewport required');
assert.match(shell,/id="storyTrack"/,'native scrolling must drive story');
assert.match(js,/root\.addEventListener\('scroll',scheduleScroll/,'scroll must drive scene progress');
assert.match(js,/--camera-zoom/,'camera zoom must be tied to scroll');
assert.match(js,/--app-opacity/,'rating reveal must track scroll');
assert.match(js,/function setupFrameReturn/,'scrolling up must support returning to intro');
assert.match(css,/position:sticky/,'scene must stay pinned during transition');
assert.match(css,/\.story-scroll-track/,'scene transition requires scroll distance');
