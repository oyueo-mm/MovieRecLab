'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const dir=path.join(__dirname,'..'),code=fs.readFileSync(path.join(dir,'showcase/v10-recommender.js'),'utf8'),markup=fs.readFileSync(path.join(dir,'showcase/index.html'),'utf8'),controller=fs.readFileSync(path.join(dir,'showcase/showcase.js'),'utf8');
new vm.Script(code);new vm.Script(controller);
assert.ok(markup.includes('v10-model.js?v=10')&&markup.includes('v10-recommender.js?v=10'));
assert.ok(markup.indexOf('ml25m-model.js')<markup.indexOf('v10-recommender.js'));
assert.ok(markup.indexOf('v10-recommender.js')<markup.indexOf('showcase.js?v=10'));
for(const option of ['auto','v9','v8','experimental','v10'])assert.ok(markup.includes('option value="'+option+'"'));
assert.match(controller,/championRows=v10\.recommend\('similarity'/);
assert.match(controller,/if\(championRows\)semanticRows=championRows/);
assert.match(controller,/v10option\.disabled/);
const rows=Array.from({length:8300},(_,i)=>[i+1,Array.from({length:24},(_,j)=>Math.round(90*Math.sin(i*.09+j*.23)))]);
const v9={films:rows.map(([id,vec])=>[id,vec,vec,600])};
const pack={version:'v10-2026',quality:{similarity:true,user:false},champion:'tag+als',blend:[.52,.48],model:{type:'als',rows}};
const run=p=>{const c={window:{MovieRecV10Data:p,MovieRec25MData:v9}};vm.runInNewContext(code,c);return c.window.MovieRecV10;};
const api=run(pack);assert.equal(api.ready(),true);
const movies=rows.map(([id])=>({id,n:500,title:'영화 '+id})),rated=[[1,5],[2,4],[3,1],[4,2],[5,5]];
const a=api.recommend('similarity',rated,movies,12);assert.ok(a?.length===12);
assert.ok(a.every(r=>r.source==='MovieLens 25M V10'&&r.method==='similarity'&&!rated.some(([id])=>id===r.movie.id)));
assert.equal(new Set(a.map(r=>r.movie.id)).size,12);
assert.deepEqual(a.map(x=>x.movie.id),api.recommend('similarity',rated,movies,12).map(x=>x.movie.id));
assert.equal(api.recommend('user',rated,movies,12),null,'no fabricated per-user 25M KNN model');
assert.equal(api.recommend('similarity',[[1,5]],movies,12),null,'insufficient ratings return to V9');
const blocked=run({...pack,quality:{similarity:false}});
assert.equal(blocked.recommend('similarity',rated,movies,12),null,'failed quality gate must preserve V9');
assert.ok(blocked.recommend('similarity',rated,movies,12,{experimental:true})?.length===12,'explicit experiment can inspect unsuccessful model');
const noData=run({version:'v10-2026',quality:{similarity:false},model:null});assert.equal(noData.ready(),false);
const knnRows=rows.map(([id])=>[id,[[((id)%8300)+1,2500],[((id+1)%8300)+1,1200]]]);
const knn=run({...pack,champion:'item-knn',model:{type:'itemknn',rows:knnRows}});
assert.equal(knn.ready(),true);assert.ok(knn.recommend('similarity',rated,movies,12)?.length===12,'sparse Item KNN learned similarities are usable');
console.log('V10 quality gating, cross-mode rollback, browser ranking, Top-K item graph and AL(S)/hybrid model inference passed.');